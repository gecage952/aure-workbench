def _scope_of(key: str) -> str:
    """Read the scope out of a table key like ``Cu.thickness@ocv1``."""
    if "@" not in key:
        return "model"
    suffix = key.split("@", 1)[1]
    if suffix == "model":
        return "model"
    return "measurement" if "#" in suffix else "state"


def _attribute_of(key: str) -> str:
    """``probe.intensity@ocv1`` -> ``intensity``."""
    head = key.split("@", 1)[0]
    return head.split(".", 1)[1] if "." in head else head


def _is_fitted(table: ParameterTable, path: str) -> bool:
    """Whether any free parameter addresses this path."""
    return any(
        parameter.key.split("@", 1)[0] == path and not parameter.fixed
        for parameter in table.free
    )


def _fixed_layers(table: ParameterTable) -> list[str]:
    """Layers with no fitted parameter at all."""
    spec = table.spec
    fitted = {
        parameter.key.split("@", 1)[0].split(".", 1)[0] for parameter in table.free
    }
    constrained = {
        expression.key.split("@", 1)[0].split(".", 1)[0]
        for expression in table.expressions
    }
    touched = fitted | constrained
    return [layer.name for layer in spec.stack if layer.name not in touched]


#: Real-space resolution limit for a typical REF_L Q_max of 0.2 1/A.
_RESOLUTION_LIMIT = 30.0


def _thin_layers(spec: Any) -> list[tuple[str, float]]:
    """Layers thinner than the resolution limit, excluding the substrate."""
    found = []
    for layer in spec.stack[:-1]:
        thickness = float(layer.thickness or 0.0)
        if 0 < thickness < _RESOLUTION_LIMIT:
            found.append((layer.name, thickness))
    return found
